"""Sets up the README clips' agent demo in a home of its own: a small Rust repo, sphered's config pointing at
fake-claude, and the script fake-claude plays (an agent adding a --json flag, tests first). Nothing here touches
the real ~/.sphere or ~/.claude.

    python3 demo.py <demo home> <dir with sphere-host and fake-claude> [pace]

pace stretches every pause (the recordings render slower than real time, so the agent has to wait for them).
"""
