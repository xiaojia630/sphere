def git(*a):
    subprocess.run(["git", "-C", repo, *a], check=True, capture_output=True)


if not os.path.isdir(os.path.join(repo, ".git")):
    os.makedirs(os.path.join(repo, "src"), exist_ok=True)
    with open(os.path.join(repo, "Cargo.toml"), "w") as f:
        f.write('[package]\nname = "wordcount"\nversion = "0.1.0"\nedition = "2021"\n\n[dependencies]\n')
    with open(os.path.join(repo, "src", "main.rs"), "w") as f:
        f.write(OLD)
    with open(os.path.join(repo, "Cargo.lock"), "w") as f:
        f.write('# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n'
                '[[package]]\nname = "wordcount"\nversion = "0.1.0"\n')
    with open(os.path.join(repo, ".gitignore"), "w") as f:
        f.write("/target\n")
    subprocess.run(["git", "init", "-q", "-b", "main", repo], check=True)
    git("config", "user.email", "dev@example.com")
    git("config", "user.name", "Dev")
    git("add", "-A")
    git("commit", "-q", "-m", "Count words")


