NEW = '''use std::env;

/// The words in `text`, split on whitespace.
fn words(text: &str) -> Vec<&str> {
    text.split_whitespace().collect()
}

/// Builds the output line: plain by default, or JSON with `--json` anywhere in `args`.
fn render(args: &[String]) -> String {
    let json = args.iter().any(|a| a == "--json");
    let text = args.iter().filter(|a| *a != "--json").cloned().collect::<Vec<_>>().join(" ");
    let words = words(&text);
    if json {
        let list = words.iter().map(|w| format!("{:?}", w)).collect::<Vec<_>>().join(", ");
        format!("{{\\"count\\": {}, \\"words\\": [{}]}}", words.len(), list)
    } else {
        format!("{} words", words.len())
    }
}

fn main() {
    let args: Vec<String> = env::args().skip(1).collect();
    println!("{}", render(&args));
}

#[cfg(test)]
mod tests {
    use super::*;

    fn args(v: &[&str]) -> Vec<String> {
        v.iter().map(|s| s.to_string()).collect()
    }

    #[test]
    fn counts_words() {
        assert_eq!(words("one two  three").len(), 3);
    }

    #[test]
    fn prints_plain_by_default() {
        assert_eq!(render(&args(&["hello", "world"])), "2 words");
    }

    #[test]
    fn prints_json_with_the_flag() {
        assert_eq!(render(&args(&["--json", "hello", "world"])), r#"{"count": 2, "words": ["hello", "world"]}"#);
    }

    #[test]
    fn the_flag_is_not_counted_as_a_word() {
        assert_eq!(render(&args(&["a", "--json"])), r#"{"count": 1, "words": ["a"]}"#);
    }
}
'''

